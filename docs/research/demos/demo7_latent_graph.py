# Displacements of ONE rotor-relation fill that rotor's 2-D plane (a great
# circle of directions), so k-means on directions cannot recover relations
# (a first version tried: 57% purity — kept in git history). The right
# object is the SUBSPACE: k-planes clustering — assign each displacement to
# the plane that best contains it, refit planes by SVD, iterate.


def k_planes(D, k, iters=30):
    """k-subspaces clustering with farthest-first seeding: seed each new
    plane from the displacement worst-explained by the planes so far, then
    alternate (assign to best-containing plane / refit plane by SVD).
    Restart selection is by the UNSUPERVISED objective (total contained
    projection mass) — never by labels."""
    n = len(D)
    i0 = int(rng.integers(n))
    u = D[i0].copy()
    v = D[(i0 + 1) % n] - (D[(i0 + 1) % n] @ u) * u
    v /= max(float(np.linalg.norm(v)), 1e-12)
    planes = [(u, v)]
    while len(planes) < k:
        proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
        worst = int(np.argmin(proj.max(axis=1)))
        u = D[worst].copy()
        partner = int(np.argsort(-np.abs(D @ u))[1])
        v = D[partner] - (D[partner] @ u) * u
        v /= max(float(np.linalg.norm(v)), 1e-12)
        planes.append((u, v))
    assign = None
    for _ in range(iters):
        proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
        assign = np.argmax(proj, axis=1)
        for c in range(k):
            m = D[assign == c]
            if len(m) >= 2:
                _, _, Vt = np.linalg.svd(m, full_matrices=False)
                planes[c] = (Vt[0], Vt[1])
    proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
    objective = float(proj.max(axis=1).sum())
    return np.argmax(proj, axis=1), planes, objective


def cluster_purity(D_in, labels_in):
    best_obj, best_assign = -1.0, None
    for _restart in range(10):
        a, p, obj = k_planes(D_in, K_REL)
        if obj > best_obj:
            best_obj, best_assign, best_planes = obj, a, p
    pur = sum(np.bincount(labels_in[best_assign == c], minlength=K_REL).max()
              for c in range(K_REL) if (best_assign == c).any())
    return 100.0 * pur / len(labels_in), best_assign, best_planes


