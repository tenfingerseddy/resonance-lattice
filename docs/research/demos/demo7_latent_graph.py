for c in range(K_REL):
    m = labels[assign == c]
    r = int(np.bincount(m, minlength=K_REL).argmax())
    u_hat, v_hat = planes[c]
    u_true, v_true, th_true = rel_planes[r]
    P_err = float(np.linalg.norm(
        np.outer(u_true, u_true) + np.outer(v_true, v_true)
        - np.outer(u_hat, u_hat) - np.outer(v_hat, v_hat), 2))
    ths = []
    for (x, y), a in zip(edges, assign):
        if a == c:
            px = np.array([x @ u_hat, x @ v_hat])
            py = np.array([y @ u_hat, y @ v_hat])
            if np.linalg.norm(px) > 0.05 and np.linalg.norm(py) > 0.05:
                px, py = px / np.linalg.norm(px), py / np.linalg.norm(py)
                ths.append(math.atan2(px[0] * py[1] - px[1] * py[0], float(px @ py)))
    th_hat = float(np.median(ths))
    for _ in range(tests // K_REL):
        x = unit_rows(rng.standard_normal((1, d_s)))[0]

        def apply_rot(u, v, th, x):
            cu, cv = float(x @ u), float(x @ v)
            return x + cu * ((math.cos(th) - 1) * u + math.sin(th) * v) \
                     + cv * (-math.sin(th) * u + (math.cos(th) - 1) * v)

        y_pred = apply_rot(u_hat, v_hat, th_hat, x)
        y_true = apply_rot(u_true, v_true, th_true, x)
        hits += int(float(y_pred @ y_true)
                    / (np.linalg.norm(y_pred) * np.linalg.norm(y_true)) > 0.95)
