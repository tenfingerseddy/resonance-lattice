def components(threshold):
    par = list(range(N))

    def f(x):
        while par[x] != x:
            par[x] = par[par[x]]
            x = par[x]
        return x

    for (i, j), s in zip(edge_list, edge_sims):
        if s >= threshold:
            ri, rj = f(i), f(j)
            if ri != rj:
                par[ri] = rj
    return np.array([f(i) for i in range(N)])


