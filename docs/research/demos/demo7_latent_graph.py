print("7c. relation types from raw pairs: k-planes clustering of displacements")

d_s, K_REL, PER = 64, 4, 150
NOISE = 0.03
FEATURE_MASS = 0.35

# Identifiability caveat, discovered by running the fully-random version
# first: a random unit concept in 64d carries only ~sqrt(2/64) ~ 0.18 of its
# mass in any fixed plane, so the rotational displacement (~ 2 sin(th/2) x
# in-plane mass) barely clears the noise floor and cluster purity degrades
# (~84% measured). Relations are recoverable where they act on entities that
# CARRY the relevant feature — modelled here by giving each edge's source
# concept >= FEATURE_MASS in-plane mass. Both numbers are reported.


def make_edges(feature_mass):
    rel_planes, edges, labels = [], [], []
    for r in range(K_REL):
        u = rng.standard_normal(d_s)
        u /= np.linalg.norm(u)
        v = rng.standard_normal(d_s)
        v -= (v @ u) * u
        v /= np.linalg.norm(v)
        th = float(rng.uniform(0.6, 1.2))
        rel_planes.append((u, v, th))
        for _ in range(PER):
            x = rng.standard_normal(d_s)
            x /= np.linalg.norm(x)
            if feature_mass > 0:
                a, b = rng.standard_normal(2)
                inplane = a * u + b * v
                inplane /= np.linalg.norm(inplane)
                x = x + feature_mass * inplane
                x /= np.linalg.norm(x)
            cu, cv = float(x @ u), float(x @ v)
            y = x + cu * ((math.cos(th) - 1) * u + math.sin(th) * v) \
                  + cv * (-math.sin(th) * u + (math.cos(th) - 1) * v)
            y = y + NOISE * rng.standard_normal(d_s)
            y /= np.linalg.norm(y)
            edges.append((x, y))
            labels.append(r)
    return rel_planes, edges, np.array(labels)


rel_planes, edges, labels = make_edges(FEATURE_MASS)
