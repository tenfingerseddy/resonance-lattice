def greedy_route(start, target, nbrs, max_hops=40, beam=1):
    frontier = [(0.0, start)]
    visited = {start}
    for hop in range(1, max_hops + 1):
        cands = []
        for _s, node in frontier:
            for nxt in nbrs(node):
                nxt = int(nxt)
                if nxt == target:
                    return hop
                if nxt not in visited:
                    visited.add(nxt)
                    cands.append((float(band[nxt] @ band[target]), nxt))
        if not cands:
            return None
        cands.sort(reverse=True)
        frontier = cands[:beam]
    return None


def best_first_route(start, target, nbrs, ef=150):
    """HNSW-style search: best-first by similarity-to-target with
    backtracking. Returns nodes expanded, or None if budget exhausted."""
    heap = [(-float(band[start] @ band[target]), start)]
    visited = {start}
    expanded = 0
    while heap and expanded < ef:
        _, node = heapq.heappop(heap)
        expanded += 1
        if node == target:
            return expanded
        for nxt in nbrs(node):
            nxt = int(nxt)
            if nxt not in visited:
                visited.add(nxt)
                heapq.heappush(heap, (-float(band[nxt] @ band[target]), nxt))
    return None


