"""Demo 7 — The latent graph: connecting vectors so they are easier to traverse.

Question under investigation (repository owner, 2026-08): can we create a
graph from vectors — connect them in a way that makes them easier to
traverse, and does an ontology fall out?

Position tested: the graph is ALREADY LATENT in an embedding band. Nodes are
given; everything else is geometry — and the honest headline of this demo is
that the geometry must be MEASURED before choosing traversal laws:

  7a  edges + navigation: kNN links + a few random long-range links make the
      band navigable — but the load-bearing ingredient is edge SYMMETRY:
      a directed kNN graph strands nodes nobody points at, and greedy
      routing on it fails a third of the time; make the links bidirectional
      (as HNSW does) and even greedy succeeds, while best-first search with
      backtracking (the algorithm inside rlat's FAISS HNSW, run in the
      open) reaches any target touching ~1% of the corpus.
  7b  a REGIME DIAGNOSTIC for sequences: the mean cosine between successive
      displacements along reading-order chains identifies the local law.
      For i.i.d. passages around a per-document centre it is exactly -1/2;
      for persistent paths it is positive. This corpus measures ~= -1/2:
      documents are CLOUDS, not paths — so momentum extrapolation (the
      path-regime tool, and this demo's original hypothesis) must LOSE to
      centroid prediction (the cloud-regime tool), and does, monotonically
      in the momentum strength. The failed hypothesis is kept on display;
      the diagnostic that replaces it transfers to any band.
  7c  relation types from raw vector pairs: displacements of a rotor-relation
      span that relation's 2-D plane, so the right mining tool is K-PLANES
      (subspace) clustering, not k-means. Planted relations are recovered
      and APPLY to unseen nodes — typed edges that are generated by
      geometry, not stored ("virtual edges"). The same displacement
      clustering finds real structural edge kinds in the corpus without
      labels (weakly at LSA quality; measured, not oversold).
  7d  hierarchy for free: single-linkage components across a threshold sweep
      nest exactly — broader/narrower (SKOS-style) concept levels, every
      concept a set of passages with source receipts.

Corpus: this repository's own docs (real text, LSA stand-in embeddings —
see corpus.py caveat), or a REAL knowledge model when a path is given:

    python3 demo7_latent_graph.py [/path/to/model.rlat]

Requires numpy. Run:  python3 demo7_latent_graph.py
"""

