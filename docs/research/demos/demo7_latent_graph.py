def rotor_extrapolate(prev, cur, t=1.0):
    """Path-regime tool: continue the geodesic past cur by t x the last angle."""
    w = float(np.clip(prev @ cur, -1.0, 1.0))
    omega = math.acos(w)
    if omega < 1e-9:
        return cur.copy()
    tang = (w * cur - prev) / math.sin(omega)
    return math.cos(t * omega) * cur + math.sin(t * omega) * tang


def norm1(x):
    return x / max(float(np.linalg.norm(x)), 1e-12)


