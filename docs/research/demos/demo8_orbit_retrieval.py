def eval_cross(mode):
    hits = total = 0
    rr = 0.0
    for _dirname, g in bench_dirs.items():
        targets = set(g["verdict"])
        for q_idx in g["design"]:
            if mode == "orbit":
                scores = np.max(np.stack([band @ x for _t, x in orbit(band[q_idx], rotors_x)]),
                                axis=0)
            else:
                B = BANDS[mode]
                scores = B @ B[q_idx]
            same_file = [i for i in range(N) if src_of[i] == src_of[q_idx]]
            scores[same_file] = -np.inf             # exclude own file entirely
            order = np.argsort(-scores)
            best = next(k for k, idx in enumerate(order) if idx in targets) + 1
            hits += int(best <= 10)
            rr += 1.0 / best
            total += 1
    return 100.0 * hits / total, rr / total


