def quotient_project(X, rotors):
    basis = []
    for r in rotors:
        for w in (r["u"], r["v"]):
            w = w.copy()
            for b_ in basis:
                w -= (w @ b_) * b_
            n = float(np.linalg.norm(w))
            if n > 1e-6:
                basis.append(w / n)
    Y = X.copy()
    for b_ in basis:
        Y = Y - np.outer(Y @ b_, b_)
    return unit_rows(Y) if Y.ndim == 2 else norm1(Y)


