"""Demo 8 — Orbit retrieval: the graph, without storing a graph.

Context: the repository owner reports that earlier graph features were
discarded — no meaningful improvement, add-on rather than core. This demo
takes that verdict as a design constraint: no stored edges, no new query
surface, no sidecar. If corpus structure is to help retrieval, it must live
in the two things the product already IS — the score function and the
coordinates.

The reformulation: **edges are instances; transformations are laws.** Mine
the corpus's recurring displacement structure once at build time as K
relation rotors (k-planes over displacement fields — validated in demo 7),
keep the ~K*(2d+1) floats, and discard every edge. Two retrieval modes fall
out, both running through the existing `scores = band @ q` path:

  orbit-max   score(q, p) = max over the query's ORBIT {q} u {R_c^{+-1} q}
              under the mined rotors — "also search for what this query
              becomes under the corpus's own moves." 2K+1 matvecs; each hit
              is tagged with the rotor that found it (a receipt).

  quotient    a tiny proposition (checked numerically below): averaging over
              the rotation group generated by a mined rotor annihilates its
              plane exactly — so group-invariant retrieval IS flat retrieval
              in a projected band with the mined planes removed. Zero
              query-time overhead; ships as a band variant.

Everything is measured on real text (this repository's own docs; LSA
stand-in embeddings — corpus.py states the caveat), with the negatives
reported as prominently as the positives. Requires numpy.

Run:  python3 demo8_orbit_retrieval.py
"""

