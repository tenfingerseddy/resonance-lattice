def rank_of(scores, target, exclude):
    s = scores.copy()
    s[exclude] = -np.inf
    return int((s > s[target]).sum()) + 1


def eval_pairs(pairs, rotors):
    flat_h5 = orb_h5 = 0
    flat_rr = orb_rr = 0.0
    for a, b in pairs:
        fr = rank_of(band @ band[a], b, [a])
        scores = np.max(np.stack([band @ x for _tag, x in orbit(band[a], rotors)]), axis=0)
        orr = rank_of(scores, b, [a])
        flat_h5 += int(fr <= 5)
        orb_h5 += int(orr <= 5)
        flat_rr += 1.0 / fr
        orb_rr += 1.0 / orr
    n = len(pairs)
    return (100.0 * flat_h5 / n, flat_rr / n), (100.0 * orb_h5 / n, orb_rr / n)


