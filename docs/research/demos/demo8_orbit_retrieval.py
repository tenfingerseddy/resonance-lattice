def unit_rows(X):
    return X / np.maximum(np.linalg.norm(X, axis=1, keepdims=True), 1e-12)


def norm1(x):
    return x / max(float(np.linalg.norm(x)), 1e-12)


# ------------------------------------------------------------- mining -----

def k_planes(D, k, iters=30, restarts=10):
    """k-subspaces clustering of displacement directions (demo 7's tool);
    restart selection by the unsupervised objective."""
    def one():
        n = len(D)
        i0 = int(rng.integers(n))
        u = D[i0].copy()
        v = D[(i0 + 1) % n] - (D[(i0 + 1) % n] @ u) * u
        v /= max(float(np.linalg.norm(v)), 1e-12)
        planes = [(u, v)]
        while len(planes) < k:
            proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
            worst = int(np.argmin(proj.max(axis=1)))
            u2 = D[worst].copy()
            partner = int(np.argsort(-np.abs(D @ u2))[1])
            v2 = D[partner] - (D[partner] @ u2) * u2
            v2 /= max(float(np.linalg.norm(v2)), 1e-12)
            planes.append((u2, v2))
        assign = None
        for _ in range(iters):
            proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
            assign = np.argmax(proj, axis=1)
            for c in range(k):
                m = D[assign == c]
                if len(m) >= 2:
                    _, _, Vt = np.linalg.svd(m, full_matrices=False)
                    planes[c] = (Vt[0], Vt[1])
        proj = np.stack([(D @ u) ** 2 + (D @ v) ** 2 for u, v in planes], axis=1)
        return np.argmax(proj, axis=1), planes, float(proj.max(axis=1).sum())

    best = max((one() for _ in range(restarts)), key=lambda t: t[2])
    return best[0], best[1]


def mine_rotors(pairs, band, k):
    """Mine K rotor prototypes (plane + angle + support) from raw index pairs.
    The angle is the median in-plane rotation of member edges whose endpoints
    both carry enough in-plane mass (demo 7's identifiability boundary);
    angles are clamped to pi/2 (demo 5's quadrature guardrail)."""
    D = unit_rows(np.stack([band[j] - band[i] for i, j in pairs]))
    assign, planes = k_planes(D, k)
    rotors = []
    for c in range(k):
        members = [p for p, a in zip(pairs, assign) if a == c]
        if len(members) < 10:
            continue
        u, v = planes[c]
        ths = []
        for i, j in members:
            px = np.array([band[i] @ u, band[i] @ v])
            py = np.array([band[j] @ u, band[j] @ v])
            if np.linalg.norm(px) > 0.05 and np.linalg.norm(py) > 0.05:
                px, py = px / np.linalg.norm(px), py / np.linalg.norm(py)
                ths.append(math.atan2(px[0] * py[1] - px[1] * py[0], float(px @ py)))
        if len(ths) < 5:
            continue
        th = float(np.clip(np.median(ths), -math.pi / 2, math.pi / 2))
        rotors.append({"u": u, "v": v, "theta": th, "support": len(members)})
    return rotors


def apply_rotor(x, u, v, theta):
    cu, cv = float(x @ u), float(x @ v)
    c, s = math.cos(theta), math.sin(theta)
    return x + cu * ((c - 1) * u + s * v) + cv * (-s * u + (c - 1) * v)


def orbit(q, rotors):
    """The query's orbit: identity + each mined rotor forward and inverse."""
    out = [("id", q)]
    for r in rotors:
        out.append((f"rot{r['theta']:+.2f}", norm1(apply_rotor(q, r["u"], r["v"], r["theta"]))))
        out.append((f"rot{-r['theta']:+.2f}", norm1(apply_rotor(q, r["u"], r["v"], -r["theta"]))))
    return out


