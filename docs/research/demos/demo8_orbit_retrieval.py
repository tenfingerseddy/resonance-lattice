# ------------------------------------------------------ 8a  the maths -----

print("8a. the quotient proposition: group-averaging == removing the mined planes")
u = norm1(rng.standard_normal(d))
v0 = rng.standard_normal(d)
v = norm1(v0 - (v0 @ u) * u)
m_ord = 5
avg = np.zeros((d, d))
for jj in range(m_ord):
    th = 2 * math.pi * jj / m_ord
    R = np.eye(d) + np.outer(u, u) * (math.cos(th) - 1) + np.outer(v, v) * (math.cos(th) - 1) \
        + (np.outer(v, u) - np.outer(u, v)) * math.sin(th)
    avg += R / m_ord
proj = np.eye(d) - np.outer(u, u) - np.outer(v, v)
check("averaging over the cyclic group C_5 of a rotor == exact plane removal",
      float(np.abs(avg - proj).max()) < 1e-12)
check("...and the result is an orthogonal projection (idempotent)",
      float(np.abs(avg @ avg - avg).max()) < 1e-12)
print("    -> group-invariant retrieval is flat retrieval in a projected band:")
print("       the 'graph' collapses into the coordinates. Zero query-time cost.")

